#!/usr/bin/env python3
"""Multi-seed synthetic recovery study -> docs/validation-study.md.

For each seed: generate a corrupted multi-cell dataset with known
truth, run the full evbatt pipeline, and record Q0 error, forecast
RMSE vs the true trajectory, PI coverage/width, anomaly F1, and EOL
error where EOL is identifiable (true EOL <= 1.5x observed window).
"""
from __future__ import annotations

import sys
from pathlib import Path

import numpy as np

sys.path.insert(0, str(Path(__file__).resolve().parents[1] / "src"))
from evbatt.io import normalize_cycles  # noqa: E402
from evbatt.models import eol_cycle, predict  # noqa: E402
from evbatt.pipeline import run_analysis  # noqa: E402
from evbatt.schemas import AnalysisConfig  # noqa: E402
from evbatt.synthetic import generate_dataset  # noqa: E402

SEEDS = [1, 2, 3, 4, 5, 6, 7, 8]
FC = [700.0, 800.0, 900.0]
CFG = AnalysisConfig(n_bootstrap=80)


def main() -> None:
    rows = []
    for seed in SEEDS:
        df, truth = generate_dataset(n_cells=3, max_cycle=700, seed=seed)
        norm, _ = normalize_cycles(df)
        res = run_analysis(norm, config=CFG, forecast_cycles=FC)
        anom = res.anomalies
        flagged = {(r.cell_id, int(r.cycle_index))
                   for r in anom[anom.qc_status == "anomaly"].itertuples()}
        tkeys = {tuple(x) for x in truth.anomaly_keys}
        tp, fp, fn = len(flagged & tkeys), len(flagged - tkeys), len(tkeys - flagged)
        f1 = 2 * tp / max(2 * tp + fp + fn, 1)
        for cell, tinfo in truth.per_cell.items():
            info = res.summary["cells"][cell]
            u = res.uncertainty[res.uncertainty.cell_id == cell].sort_values("cycle_index")
            true = predict(tinfo["model"], tinfo["params"], np.asarray(FC))
            fc_rmse = float(np.sqrt(np.mean((u.soh_predicted.to_numpy() - true) ** 2))) \
                if len(u) else np.nan
            cov = float(np.mean((true >= u.pi_lo.to_numpy()) & (true <= u.pi_hi.to_numpy()))) \
                if len(u) else np.nan
            width = float(np.mean(u.pi_hi - u.pi_lo)) if len(u) else np.nan
            q0_err = abs(info["reference_capacity_Ah"] - tinfo["Q0_true_Ah"]) / tinfo["Q0_true_Ah"]
            true_eol = eol_cycle(tinfo["model"], tinfo["params"], 0.80, 20000)
            est_eol = info.get("eol_cycle")
            eol_err = (abs(est_eol - true_eol) / true_eol
                       if true_eol and est_eol and true_eol <= 1050 else np.nan)
            rows.append({"seed": seed, "cell": cell, "q0_err": q0_err, "fc_rmse": fc_rmse,
                         "coverage": cov, "width": width, "eol_err": eol_err, "f1": f1})
        print(f"seed {seed} done")
    import pandas as pd
    d = pd.DataFrame(rows)
    agg = {c: (float(np.nanmedian(d[c])), float(np.nanmax(d[c]))) for c in
           ["q0_err", "fc_rmse", "coverage", "width", "eol_err", "f1"]}
    lines = ["# Synthetic validation study (generated by scripts/validation_study.py)", "",
             f"{len(SEEDS)} seeds x 3 cells = {len(d)} cell experiments; forecasts at "
             f"{[int(x) for x in FC]} cycles (data window 700); 95% bootstrap PIs "
             f"(n=80). EOL error reported only where true EOL <= 1050 (identifiable).", "",
             "| Metric | Median | Worst (max; coverage/F1: min) |", "|---|---:|---:|"]
    for c, (med, mx) in agg.items():
        worst = float(np.nanmin(d[c])) if c in ("coverage", "f1") else mx
        lines.append(f"| {c} | {med:.4f} | {worst:.4f} |")
    lines += ["", "Interpretation (read honestly): medians sit inside the "
              "benchmark task's tolerances, but worst-case seeds exceed them -- "
              "small injected outliers (down to x0.97) are partly undetectable "
              "in principle, capping F1; generator drift is not part of the "
              "scored truth model, inflating forecast error; and PI coverage at "
              "extrapolated cycles runs well below nominal 95% (residual "
              "independence assumption). The benchmark therefore uses "
              "seed-screened identifiable instances with thresholds calibrated "
              "on two independent implementations, while these random-seed "
              "numbers describe general method variability. See README."]
    out = Path(__file__).resolve().parents[1] / "docs/validation-study.md"
    out.write_text("\n".join(lines) + "\n")
    print(out.read_text())


if __name__ == "__main__":
    main()
